import {
  failure,
  success,
  type OperationResult,
} from "@/shared/contracts/operation-result";
import type {
  RaceCheckpoint,
  RaceItem,
  RaceItemType,
  RacePlayer,
  RaceState,
} from "../contracts/race";

export const RACE_CHECKPOINTS = [25, 50, 75] as const;
export const FOG_DURATION_MS = 4000;
export function raceProgress(player: Pick<RacePlayer, "progress" | "text">) {
  return player.text.length ? player.progress / player.text.length : 0;
}
function byProgress(a: RacePlayer, b: RacePlayer) {
  return (
    raceProgress(b) - raceProgress(a) ||
    a.playerIdentityId.localeCompare(b.playerIdentityId)
  );
}
function attackTarget(race: RaceState, player: RacePlayer) {
  const leader = race.players
    .filter((p) => p.status === "TYPING")
    .sort(byProgress)[0];
  return leader && leader !== player ? leader : undefined;
}
function removableWords(player: RacePlayer) {
  // Keep the first word with letters left to type, including at an exact word boundary.
  // This prevents a shortcut from producing text === draft with a still-active racer.
  const current = [...player.text.matchAll(/\S+/g)].find(
    (word) => word.index + word[0].length > player.draft.length,
  );
  return current
    ? [
        ...player.text
          .slice(current.index + current[0].length)
          .matchAll(/\s+\S+/g),
      ]
    : [];
}
function drawItem(
  race: RaceState,
  player: RacePlayer,
  checkpoint: RaceCheckpoint,
  now: number,
): RaceItemType {
  const pool: RaceItemType[] = ["nudge", "nudge"];
  if (removableWords(player).length)
    pool.push("shortcut", "shortcut", "shortcut", "shortcut");
  if (attackTarget(race, player))
    pool.push("detour", "detour", "detour", "fog", "fog", "fog");
  if (!player.shield) pool.push("shield", "shield");
  if ((player.fogUntil ?? 0) > now)
    pool.push("clear", "clear", "clear", "clear");
  // FNV-1a: reproducible across reads/restarts. The race ID is generated by the server.
  let hash = 2166136261;
  for (const char of `${race.id}:${player.playerIdentityId}:${checkpoint}`) {
    hash = Math.imul(hash ^ char.charCodeAt(0), 16777619) >>> 0;
  }
  return pool[hash % pool.length];
}
function distributeLegacyBoxes(race: RaceState, now: number): void {
  if (!race.settings.bonuses || race.endedAt !== null || now < race.startsAt)
    return;
  const competitors = race.players.filter(
    (p) => p.status === "TYPING" || p.status === "FINISHED",
  );
  if (!competitors.length) return;
  const leader = competitors.reduce((best, player) =>
    raceProgress(player) > raceProgress(best) ? player : best,
  );
  const leaderProgress = raceProgress(leader);
  const lastProgress = Math.min(...competitors.map(raceProgress));
  for (const checkpoint of RACE_CHECKPOINTS) {
    if (
      race.checkpoints.includes(checkpoint) ||
      leaderProgress * 100 < checkpoint
    )
      continue;
    race.checkpoints.push(checkpoint);
    for (const player of competitors) {
      const progress = raceProgress(player);
      if (
        player.status !== "TYPING" ||
        player.bonusesReceived >= 3 ||
        progress >= leaderProgress
      )
        continue;
      // Compare integer cross-products so 55% - 30% is exactly 25 points.
      const moreThan25Points =
        4 *
          (leader.progress * player.text.length -
            player.progress * leader.text.length) >
        leader.text.length * player.text.length;
      if (progress !== lastProgress && !moreThan25Points) continue;
      const item: RaceItem = {
        id: `${checkpoint}:${player.playerIdentityId}`,
        type: drawItem(race, player, checkpoint, now),
        checkpoint,
        receivedAt: now,
        usedAt: null,
      };
      player.items.push(item);
      player.bonusesReceived++;
      race.events.push({
        id: `${item.id}:received`,
        type: item.type,
        actorId: player.playerIdentityId,
        targetId: player.playerIdentityId,
        outcome: "received",
        at: now,
      });
    }
  }
}
// Return a whole-word shortening toward half the current rank, never into first.
function catchUpWordCount(race: RaceState, player: RacePlayer) {
  const racers = race.players
    .filter((p) => p.status === "TYPING" || p.status === "FINISHED")
    .sort(byProgress);
  const rank = racers.indexOf(player) + 1;
  if (rank <= 2 || racers.length < 4 || player.progress <= 0) return 0;
  const targetRank = Math.max(2, Math.ceil(rank / 2));
  const target =
    (raceProgress(racers[targetRank - 2]) +
      raceProgress(racers[targetRank - 1])) /
    2;
  if (target <= raceProgress(player)) return 0;
  const words = removableWords(player);
  let length = player.text.length;
  let count = 0;
  for (let index = words.length - 1; index >= 0; index--) {
    length -= words[index][0].length;
    if (player.progress / length > target) break;
    count++;
  }
  return count;
}
function drawPersonalItem(
  race: RaceState,
  player: RacePlayer,
  checkpoint: RaceCheckpoint,
  now: number,
) {
  const racers = race.players
    .filter((p) => p.status === "TYPING" || p.status === "FINISHED")
    .sort(byProgress);
  const rank = racers.indexOf(player) + 1;
  const strength: 1 | 2 | 3 =
    rank <= Math.max(2, Math.ceil(racers.length / 3))
      ? 1
      : rank > Math.ceil((racers.length * 2) / 3)
        ? 3
        : 2;
  const pool: RaceItemType[] = [];
  if (removableWords(player).length)
    pool.push(
      "nudge",
      ...(rank > 1 ? (["shortcut", "shortcut"] as const) : []),
    );
  if (!player.shield) pool.push("shield");
  if ((player.fogUntil ?? 0) > now) pool.push("clear", "clear");
  const target = attackTarget(race, player);
  if (rank > 1 && target) {
    pool.push("detour");
    if (target.shield || (target.fogUntil ?? 0) <= now) pool.push("fog");
  }
  if (
    strength === 3 &&
    racers.length >= 4 &&
    catchUpWordCount(race, player) > 0
  )
    pool.push("catchup", "catchup", "catchup", "catchup", "catchup", "catchup");
  if (!pool.length) return null;
  let hash = 2166136261;
  for (const char of `${race.id}:${player.playerIdentityId}:${checkpoint}`)
    hash = Math.imul(hash ^ char.charCodeAt(0), 16777619) >>> 0;
  return { type: pool[hash % pool.length], strength };
}
export function distributeMysteryBoxes(race: RaceState, now: number): void {
  if ((race.bonusRulesVersion ?? 1) === 1)
    return distributeLegacyBoxes(race, now);
  if (!race.settings.bonuses || race.endedAt !== null || now < race.startsAt)
    return;
  // Resolve each pickup in order in the same transaction, using its current rank.
  for (const player of race.players) {
    if (player.status !== "TYPING") continue;
    // Resume useful objects from races saved before automatic activation existed.
    for (const item of player.items)
      if (item.usedAt === null && item.receivedAt <= now)
        applyRaceItem(race, player, item, now);
    const collected = (player.boxCheckpoints ??= []);
    const reached = RACE_CHECKPOINTS.filter(
      (checkpoint) =>
        !collected.includes(checkpoint) &&
        player.progress * 100 >= checkpoint * player.text.length,
    );
    for (const checkpoint of reached) {
      collected.push(checkpoint);
      if (player.bonusesReceived >= 3) continue;
      const draw = drawPersonalItem(race, player, checkpoint, now);
      if (!draw) continue;
      const item: RaceItem = {
        id: `${checkpoint}:${player.playerIdentityId}`,
        ...draw,
        checkpoint,
        receivedAt: now,
        usedAt: null,
      };
      player.items.push(item);
      player.bonusesReceived++;
      race.events.push({
        id: `${item.id}:received`,
        type: item.type,
        actorId: player.playerIdentityId,
        targetId: player.playerIdentityId,
        outcome: "received",
        at: now,
      });
      applyRaceItem(race, player, item, now);
    }
  }
}
export function applyRaceItem(
  race: RaceState,
  player: RacePlayer,
  item: RaceItem,
  now: number,
): OperationResult<void> {
  let target = player;
  let blocked = false;
  if (item.type === "detour" || item.type === "fog") {
    const leader = attackTarget(race, player);
    if (!leader) return failure("CONFLICT");
    target = leader;
    if (target.shield) {
      target.shield = false;
      blocked = true;
    } else if (item.type === "detour") {
      const words =
        race.settings.language === "fr"
          ? ["encore", "trois", "mots"]
          : ["three", "more", "words"];
      target.text += " " + words.slice(0, item.strength ?? 3).join(" ");
      target.textRevision++;
    } else {
      if ((target.fogUntil ?? 0) > now) return failure("CONFLICT");
      target.fogUntil =
        now +
        (item.strength === 1
          ? 1500
          : item.strength === 2
            ? 2500
            : FOG_DURATION_MS);
    }
  } else if (
    item.type === "shortcut" ||
    item.type === "nudge" ||
    item.type === "catchup"
  ) {
    const words = removableWords(player);
    if (!words.length) return failure("CONFLICT");
    // Remove from the suffix; this also preserves all queued edits in the current word.
    const count =
      item.type === "catchup"
        ? catchUpWordCount(race, player)
        : Math.min(
            item.type === "shortcut" ? (item.strength ?? 3) : 1,
            words.length,
          );
    if (!count) return failure("CONFLICT");
    player.text = player.text.slice(
      0,
      player.text.length -
        words.slice(-count).reduce((n, match) => n + match[0].length, 0),
    );
    player.textRevision++;
  } else if (item.type === "shield") {
    if (player.shield) return failure("CONFLICT");
    player.shield = true;
  } else {
    if ((player.fogUntil ?? 0) <= now) return failure("CONFLICT");
    player.fogUntil = null;
  }
  item.usedAt = now;
  race.events.push({
    id: `${item.id}:used`,
    type: item.type,
    actorId: player.playerIdentityId,
    targetId: target.playerIdentityId,
    outcome: blocked ? "blocked" : "applied",
    at: now,
  });
  return success(undefined);
}
